-- Minimal schema for the standalone tracked-channel scaffold.
create table if not exists public.channels (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  event_type text not null,
  page_path text not null,
  channel_slug text,
  occurred_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create index if not exists analytics_events_page_path_idx
  on public.analytics_events (page_path);
create index if not exists analytics_events_channel_slug_idx
  on public.analytics_events (channel_slug);

insert into public.channels (name, slug, active)
values ('TaNaRedeEdit', 'tanaredeedit', true)
on conflict (slug) do update
set name = excluded.name, active = excluded.active;

alter table public.channels enable row level security;
alter table public.analytics_events enable row level security;

-- Public visitor clients may record only page views for this channel.
drop policy if exists "allow_tanaredeedit_page_view_insert" on public.analytics_events;
create policy "allow_tanaredeedit_page_view_insert"
  on public.analytics_events
  for insert
  to anon, authenticated
  with check (
    event_type = 'page_view'
    and page_path = '/TaNaRedeEdit'
    and channel_slug = 'tanaredeedit'
  );

-- The public site can read active channel names if needed, but cannot mutate channels.
drop policy if exists "public_read_active_channels" on public.channels;
create policy "public_read_active_channels"
  on public.channels
  for select
  to anon, authenticated
  using (active = true);
